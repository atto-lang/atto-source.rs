//! Independent emitted-Wasm fuel-guard regression checks.
//! These read the real code section emitted by the Rust compiler, not source
//! markers or the host-only checkpoint oracle. They do not prove optimizer
//! charge-preservation or sandbox security.
use atto_compiler::{compile, compile_actor};

fn read_uleb(bytes: &[u8], cursor: &mut usize) -> usize {
    let mut result=0usize;
    let mut shift=0;
    loop {
        assert!(*cursor < bytes.len(), "bounded LEB length");
        let b=bytes[*cursor];
        *cursor+=1;
        assert!(shift < usize::BITS as usize, "LEB shift overflow");
        result |= ((b & 0x7f) as usize) << shift;
        if b & 0x80 == 0 {return result;}
        shift+=7;
    }
}
fn function_bodies(wasm: &[u8]) -> Vec<&[u8]> {
    assert!(wasm.starts_with(b"\0asm\x01\0\0\0"), "valid Wasm header");
    let mut at=8;
    while at < wasm.len() {
        let section=wasm[at];at+=1;
        let size=read_uleb(wasm,&mut at);
        let end=at.checked_add(size).expect("bounded section");
        assert!(end<=wasm.len(),"section inside module");
        if section==10 {
            let mut body_cursor=at;
            let count=read_uleb(wasm,&mut body_cursor);
            let mut bodies=Vec::new();
            for _ in 0..count {
                let len=read_uleb(wasm,&mut body_cursor);
                let body_end=body_cursor.checked_add(len).expect("bounded body");
                assert!(body_end<=end,"body inside section");
                bodies.push(&wasm[body_cursor..body_end]);
                body_cursor=body_end;
            }
            assert_eq!(body_cursor,end,"no hidden bytes after code bodies");
            return bodies;
        }
        at=end;
    }
    panic!("Wasm code section missing")
}
// The complete immediate guard and fuel debit, generated by Emit::actor_poll.
// global.get 6; i64.const 1; i64.le_u; if unreachable; end;
// global.get 6; i64.const 1; i64.sub; global.set 6
const FUEL_GUARD: &[u8]=&[
    0x23,0x06,0x42,0x01,0x58,0x04,0x40,0x00,0x0b,
    0x23,0x06,0x42,0x01,0x7d,0x24,0x06,
];
fn guards(code: &[u8]) -> usize {
    code.windows(FUEL_GUARD.len()).filter(|w|*w==FUEL_GUARD).count()
}
fn total_guards(source: &str) -> usize {
    function_bodies(&compile_actor(source).expect("actor compiles"))
        .iter().map(|body|guards(body)).sum()
}
#[test]
fn scalar_handler_has_entry_and_return_guards() {
    let src="define actor Worker as receive(int value): int { return value; } end";
    let wasm=compile_actor(src).expect("actor");
    let bodies=function_bodies(&wasm);
    assert_eq!(bodies.len(),8,"five shared helpers, actor handler, synthetic main and wrapper");
    assert_eq!(guards(bodies[5]),2,"function-entry and return statement");
    assert_eq!(guards(bodies[6]),2,"synthetic main is also instrumented");
    assert_eq!(guards(bodies[7]),0,"public wrapper has private entry gate but is not user code");
    assert_eq!(total_guards(src),4);
}
#[test]
fn straight_line_statements_add_fuel_guards() {
    let one="define actor Worker as receive(int value): int { return value; } end";
    let two="define actor Worker as receive(int value): int { let x = value + 1; return x; } end";
    let three="define actor Worker as receive(int value): int { let x = value + 1; x = x + 1; return x; } end";
    assert_eq!(total_guards(one),4);
    assert_eq!(total_guards(two),5);
    assert_eq!(total_guards(three),6);
}
#[test]
fn continue_path_and_empty_loop_header_are_always_instrumented() {
    let basic="define actor Worker as receive(int value): int { let i = 0; while i < value do i = i + 1; done return i; } end";
    let with_continue="define actor Worker as receive(int value): int { let i = 0; while i < value do i = i + 1; continue; done return i; } end";
    assert_eq!(total_guards(basic),8,"entry, statements, loop header, synthetic main");
    assert_eq!(total_guards(with_continue),9,"continue adds a separate charge");
    let empty="define actor Worker as receive(int value): int { while true do done return value; } end";
    assert!(total_guards(empty)>=6,"the empty infinite loop still has an iteration charge");
}
#[test]
fn non_actor_main_is_unmodified_by_actor_only_metering() {
    let bytes=compile("pub fnc main(): int { return 42; }").expect("ordinary program");
    assert_eq!(function_bodies(&bytes).iter().map(|b|guards(b)).sum::<usize>(),0);
}
#[test]
fn actor_guest_does_not_export_meter_globals() {
    let wasm=compile_actor("define actor Worker as receive(int value): int { return value; } end").unwrap();
    let mut at=8usize;
    while at<wasm.len() {
        let section=wasm[at];at+=1;
        let size=read_uleb(&wasm,&mut at);
        let end=at+size;
        if section==7 {
            let mut p=at;
            assert_eq!(read_uleb(&wasm,&mut p),1,"one actor export");
            let n=read_uleb(&wasm,&mut p);
            assert_eq!(&wasm[p..p+n],b"receive");
            p+=n;
            assert_eq!(wasm[p],0,"function export only");
            return;
        }
        at=end;
    }
    panic!("export section missing");
}
