// Native attoc -> actual guest Wasm -> physical memory proof.
// Run after: cargo build --bin attoc
// This does not certify general arrays, actor transfer, mutable borrows or SIMD.
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join, resolve, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, 'fixtures/pass/collection-layout-soa-15.atto');
const attoc = process.env.ATTOC ?? resolve(here, '../target/debug/attoc');
assert.ok(existsSync(attoc), 'real attoc compiler binary not found: ' + attoc);
const sha256 = b => createHash('sha256').update(b).digest('hex');
const work = mkdtempSync(join(tmpdir(), 'atto-real-soa-guest-'));
try {
  const target = join(work, 'soa-15.wasm');
  const built = spawnSync(attoc, [src, '-o', target], {
    encoding: 'utf8', timeout: 30_000, maxBuffer: 1 << 20,
  });
  assert.equal(built.error, undefined, 'compiler process failed');
  assert.equal(built.status, 0, 'source compiler rejected valid layout program: ' + built.stderr);
  const wasm = readFileSync(target);
  assert.ok(WebAssembly.validate(wasm), 'generated bytes are not a valid Wasm module');
  const module = new WebAssembly.Module(wasm);
  assert.deepEqual(WebAssembly.Module.imports(module), [], 'guest must not use host code for storage');
  const instance = new WebAssembly.Instance(module, {});
  const result = instance.exports.main();
  assert.equal(result, 15n, 'actual guest return value');
  assert.equal(instance.exports.panic_code.value, 0, 'guest panic');
  const memory = instance.exports.memory;
  assert.ok(memory instanceof WebAssembly.Memory, 'physical guest memory is not exported');
  const bytes = new Uint8Array(memory.buffer);
  const actual = Array.from({length: 6}, (_, i) => {
    const buffer = new ArrayBuffer(8);
    const view = new DataView(buffer);
    view.setBigInt64(0, [15n,30n,20n,40n,1n,2n][i], true);
    return new Uint8Array(buffer);
  });
  const expected = Uint8Array.from(actual.flatMap(a => [...a]));
  const offsets = [];
  for (let i=0; i<=bytes.length-expected.length; i+=8) {
    if (bytes.subarray(i, i+expected.length).every((v,k) => v === expected[k])) {
      offsets.push(i);
    }
  }
  assert.equal(offsets.length, 1, 'exact physical SoA i64 column sequence must exist once');
  const originalRows = [10n,20n,1n,30n,40n,2n];
  assert.notDeepEqual(
    Array.from({length:6}, (_,i) => new DataView(bytes.buffer).getBigInt64(offsets[0] + i*8, true)),
    originalRows, 'row-major AoS storage is not accepted as proof of SoA'
  );
  console.log(JSON.stringify({
    kind: 'ACTUAL_SOURCE_COMPILED_GUEST',
    source_sha256: sha256(readFileSync(src)),
    compiler_binary_sha256: sha256(readFileSync(attoc)),
    wasm_sha256: sha256(wasm),
    guest_result: String(result),
    soa_physical_words: ['15','30','20','40','1','2'],
    soa_byte_offset: offsets[0],
    wasm_guest_executed: true,
    storage_evidence: 'six contiguous i64 column-major guest memory cells; no host storage imports',
    source_commit_sha: process.env.ATTO_COMPILER_SOURCE_SHA ?? null,
  }, null, 2));
} finally {
  rmSync(work, {recursive: true, force: true});
}
