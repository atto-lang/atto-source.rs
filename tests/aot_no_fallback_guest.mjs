// Direct executable conformance for the closed-world Atto Rust -> Wasm subset.
// IMPORTANT: Node's Wasm engine may use JIT internally. This proves AOT source
// lowering and real guest execution, NOT machine-native full AOT or no-engine-JIT.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = fileURLToPath(new URL('../', import.meta.url));
const attoc = resolve(process.env.ATTOC || join(repo, 'target/release/attoc'));
const temp = mkdtempSync(join(tmpdir(), 'atto-aot-guest-'));
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const positive = [
  ['scalar-42', 'fixtures/pass/01-answer.atto', 42n],
  ['recursive-55', 'fixtures/pass/19-recursion-fib.atto', 55n],
  ['lexical-lambda-42', 'fixtures/pass/lambda-direct-int.atto', 42n],
  ['tagged-option-55', 'fixtures/pass/85-option-some-match.atto', 55n],
];
const negative = [
  ['no-runtime-eval', 'pub fnc main(): int { return eval("40 + 2"); }'],
  ['no-runtime-source-compiler', 'pub fnc main(): int { return compile_source("40 + 2"); }'],
  ['no-arbitrary-reflection', 'pub fnc main(): int { return reflect_call(42, "add", 1); }'],
  ['no-dynamic-native-symbol', 'pub fnc main(): int { return load_native_symbol("lib", "f"); }'],
  ['no-runtime-type-construction', 'pub fnc main(): int { return new_type("Unknown"); }'],
];
const compiled = [];
const rejected = [];

function invoke(source, out) {
  const result = spawnSync(attoc, [source, '-o', out], {
    encoding: 'utf8', timeout: 60_000, maxBuffer: 1 << 20,
  });
  assert.equal(result.error, undefined, 'compiler must run: ' + source);
  assert.notEqual(result.status, null, 'compiler timed out or was signaled: ' + source);
  return result;
}

try {
  for (const [id, relative, expected] of positive) {
    const source = join(repo, 'tests', relative);
    const first = join(temp, id + '.wasm');
    const second = join(temp, id + '-repeat.wasm');
    const r1 = invoke(source, first);
    assert.equal(r1.status, 0, id + ': compile rejected: ' + r1.stderr);
    assert.equal(r1.stdout, '', id + ': -o compiler must not stream bytes to stdout');
    assert.ok(existsSync(first), id + ': no binary emitted');
    const bytes = readFileSync(first);
    assert.ok(WebAssembly.validate(bytes), id + ': generated bytes are not a real Wasm module');
    const module = new WebAssembly.Module(bytes);
    assert.deepEqual(WebAssembly.Module.imports(module), [], id + ': pure profile has host imports');
    const exports = WebAssembly.Module.exports(module).map(x => x.name);
    assert.ok(exports.includes('main') && exports.includes('panic_code'),
      id + ': required guest exports missing');
    const guest = new WebAssembly.Instance(module, {});
    assert.equal(typeof guest.exports.main, 'function', id + ': main not callable');
    assert.equal(guest.exports.main(), expected, id + ': executed guest returned wrong value');
    assert.equal(guest.exports.panic_code.value, 0, id + ': unexpected language panic');
    const r2 = invoke(source, second);
    assert.equal(r2.status, 0, id + ': repeat compile failed: ' + r2.stderr);
    assert.deepEqual(readFileSync(second), bytes, id + ': nondeterministic binary codegen');
    compiled.push({ id, guest_executed: true, wasm_sha256: sha256(bytes),
      expected_main_i64: expected.toString(), import_count: 0 });
  }

  for (const [id, source] of negative) {
    const file = join(temp, id + '.atto');
    writeFileSync(file, source + '\n', 'utf8');
    let code = null;
    for (let attempt = 0; attempt < 2; attempt++) {
      const out = join(temp, id + '-attempt-' + attempt + '.wasm');
      const result = invoke(file, out);
      assert.equal(result.status, 1, id + ': unsupported runtime facility must fail compilation');
      assert.ok(!existsSync(out), id + ': rejected program emitted a runnable artifact');
      assert.equal(result.stdout, '', id + ': rejected program streamed guest bytes');
      const match = result.stderr.match(/\bE_[A-Z0-9_]+\b/);
      assert.ok(match, id + ': require stable typed error diagnostic: ' + result.stderr);
      if (code !== null) assert.equal(match[0], code, id + ': diagnostic code changed');
      code = match[0];
    }
    rejected.push({ id, status: 'rejected_no_artifact', diagnostic_code: code });
  }
  process.stdout.write(JSON.stringify({
    schema: 'atto.aot-closed-world-guest-smoke.v1',
    profile: 'rust-source-to-wasm',
    proof_scope: 'source_aot_codegen_plus_real_node_wasm_guest_execution',
    runtime_engine_jit_disabled: false,
    native_aot_proven: false,
    compiler_path: attoc,
    compiler_sha256: sha256(readFileSync(attoc)),
    compiled, rejected,
  }, null, 2) + '\n');
} finally {
  rmSync(temp, { recursive: true, force: true });
}
